//! BREE Language Tier Definitions.
//!
//! 4 tiers based on enterprise density, modernization urgency, and available tooling.
//! Sources: Reuters 2017, IBM, Forrester/Deloitte 2020, TIOBE 2025, Stack Overflow 2024.

use serde::{Deserialize, Serialize};
use strum::{Display, EnumIter, EnumString};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Display, EnumIter, EnumString)]
pub enum Tier {
    #[strum(serialize = "Tier 1 — Critical")]
    Tier1,
    #[strum(serialize = "Tier 2 — High Value")]
    Tier2,
    #[strum(serialize = "Tier 3 — Specialist")]
    Tier3,
    #[strum(serialize = "Tier 4 — Long Tail")]
    Tier4,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Display, EnumIter, EnumString)]
pub enum LanguageFamily {
    #[strum(serialize = "IBM i")]
    IbmI,
    #[strum(serialize = "Mainframe (z/OS)")]
    Mainframe,
    #[strum(serialize = "NATURAL/Adabas")]
    NaturalAdabas,
    #[strum(serialize = "SAP/ABAP")]
    SapAbap,
    #[strum(serialize = "Windows Legacy")]
    WindowsLegacy,
    #[strum(serialize = "Web Legacy")]
    WebLegacy,
    #[strum(serialize = "Scientific")]
    Scientific,
    #[strum(serialize = "Safety-Critical")]
    SafetyCritical,
    #[strum(serialize = "Database Logic")]
    DatabaseLogic,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Display, EnumIter, EnumString)]
pub enum ParserStatus {
    Available,
    Partial,
    Stub,
    Planned,
    Community,
}

