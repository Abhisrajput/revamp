/// Get all languages (matrix + database logic) in a flat list.
pub fn all_languages() -> Vec<&'static LanguageEntry> {
    let mut all: Vec<&LanguageEntry> = LANGUAGE_MATRIX.iter().collect();
    all.extend(DATABASE_LOGIC_LANGUAGES.iter());
    all
}

/// Get languages by tier.
pub fn languages_by_tier(tier: Tier) -> Vec<&'static LanguageEntry> {
    all_languages().into_iter().filter(|l| l.tier == tier).collect()
}

/// Get languages by family.
pub fn languages_by_family(family: LanguageFamily) -> Vec<&'static LanguageEntry> {
    all_languages().into_iter().filter(|l| l.family == family).collect()
}

/// Find a language entry by ID.
pub fn find_language(id: &str) -> Option<&'static LanguageEntry> {
    all_languages().into_iter().find(|l| l.id == id)
}
